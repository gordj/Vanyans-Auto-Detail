"""Regenerates the city landing pages inside template.html from cities.json.

Run after editing cities.json:   python gencities.py
Then rebuild:                    powershell -ExecutionPolicy Bypass -File build.ps1
"""
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
cities = json.load(open(os.path.join(ROOT, "cities.json"), encoding="utf-8"))
by_name = {c["name"]: c for c in cities}
e = html.escape

START, END = "<!-- CITIES:START (generated by gencities.py, do not edit by hand) -->", "<!-- CITIES:END -->"

ZONE = {
    "core": ("Core coverage", "Same-day slots are most often available in {n}.",
             "{n} is in our core area, so same-day openings come up most often."),
    "standard": ("Standard coverage", "We usually book {n} a day or two out.",
                 "{n} is in our standard area. It is usually booked a day or two out."),
}


def near_links(c):
    out = []
    for n in c["near"]:
        other = by_name.get(n)
        if other and other["key"] != c["key"]:
            out.append('<a href="#/%s">%s</a>' % (other["key"], e(n)))
        else:
            out.append(e(n))
    return " &middot; ".join(out)


def page(c):
    n = e(c["name"])
    label, _, when = ZONE[c["zone"]]
    when = when.format(n=n)
    spots = "\n".join(
        '        <div class="card"><p style="color:var(--ink-2)">%s.</p></div>' % e(s.rstrip("."))
        for s in c["spots"]
    )
    return f"""<main data-page="{c['key']}" hidden>
  <section>
    <div class="wrap">
      <div class="sec-head">
        <span class="eyebrow">{label} &middot; {n}</span>
        <h1>Mobile car detailing in {n}.</h1>
        <p>{e(c['lead'])}</p>
      </div>
      <div class="cards">
        <a class="card" href="#/services?tab=full">
          <h3>Full Detail</h3>
          <p>Bring back that fresh-car feeling. Thorough interior care and a gleaming exterior wash.</p>
          <span class="from">From<b>$185</b></span>
        </a>
        <a class="card lead" href="#/services?tab=full">
          <span class="badge">Most booked</span>
          <h3>Premium Detail</h3>
          <p>Our fan-favorite deep clean. Stubborn stains out and a deep, high-gloss shine.</p>
          <span class="from">From<b>$265</b></span>
        </a>
        <a class="card" href="#/services?tab=full">
          <h3>Signature Detail</h3>
          <p>Pure automotive luxury. Our most complete detail, inside and out.</p>
          <span class="from">From<b>$385</b></span>
        </a>
      </div>
      <div style="margin-top:30px"><a class="lux-link" href="#/services">Full pricing</a></div>
    </div>
  </section>

  <section class="rule">
    <div class="wrap">
      <div class="sec-head">
        <span class="eyebrow">Around {n}</span>
        <h2>Where we work in {n}.</h2>
      </div>
      <div class="cards">
{spots}
      </div>
    </div>
  </section>

  <section class="rule">
    <div class="wrap">
      <div class="sec-head">
        <span class="eyebrow">How it works</span>
        <h2>Nothing for you to set up.</h2>
        <p>We bring our own water and power, so there is no hose to run and no cord to plug in. {when}</p>
      </div>
      <div style="display:flex; flex-wrap:wrap; gap:14px; margin-top:8px">
        <a class="btn btn-primary gloss" href="#/book">Book a detail</a>
        <a class="btn" href="tel:+18186605845" style="border-color:var(--line-2)">Call or text 818.660.5845</a>
      </div>
    </div>
  </section>

  <section class="plans-faq">
    <div class="wrap">
      <span class="eyebrow">{n} questions</span>
      <h2>Good to know before you book.</h2>
      <div class="faq">
        <details>
          <summary>How much does a detail cost in {n}?</summary>
          <p>Full Detail starts at $185, Premium Detail at $265 and Signature Detail at $385. The price is the same in {n} as anywhere else we cover, with no travel charge.</p>
        </details>
        <details>
          <summary>How soon can you come to {n}?</summary>
          <p>{when} Call or text 818-660-5845 and we will give you the next opening.</p>
        </details>
        <details>
          <summary>Do I have to be home?</summary>
          <p>No. Leave the keys or leave the car unlocked. You get a message when we arrive and another when it is done, with photos.</p>
        </details>
        <details>
          <summary>Do you bring your own water and power?</summary>
          <p>Yes. Our rig carries its own filtered water and power, so we can work in a driveway, on the street, in a parking structure or at your workplace.</p>
        </details>
      </div>
    </div>
  </section>

  <section class="rule">
    <div class="wrap">
      <div class="sec-head">
        <span class="eyebrow">Nearby</span>
        <h2>Also serving neighbors around {n}.</h2>
        <p>{near_links(c)}</p>
        <p><a class="lux-link" href="#/area">See the full service area</a></p>
      </div>
    </div>
  </section>
</main>
"""


block = START + "\n" + "\n".join(page(c) for c in cities) + END + "\n"

tpl_path = os.path.join(ROOT, "template.html")
t = open(tpl_path, encoding="utf-8").read()
if START in t:
    t = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n", lambda m: block, t, flags=re.S)
else:
    anchor = "<!-- ==================== ABOUT"
    i = t.index(anchor)
    t = t[:i] + block + "\n" + t[i:]
open(tpl_path, "w", encoding="utf-8").write(t)
print("wrote %d city pages" % len(cities))
